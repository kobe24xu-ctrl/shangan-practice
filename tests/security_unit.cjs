// Pure state-boundary tests; browser rendering is covered separately.
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const sandbox = { window: {}, URL };
vm.createContext(sandbox);
for (const file of ['app/security.js', 'app/data/bank.js']) vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), sandbox);
const s = sandbox.window.SAS_SECURITY;
const bank = sandbox.window.BANK;
const base = { v: 1, createdAt: 1, lastActive: 1, settings: {goal: 20, instant: true, shuffle: true, theme: 'auto', ai: {key: '', remember: true, provider: 'custom', base: 'https://local-ai.invalid/v1', model: 'test', cloudEndpoint: '', publishableKey: '', cloudModel: '', cloudModels: [], proxy: 'auto', priceIn: 2, priceOut: 8, temperature: .4, dailyCalls: 40, maxTokens: 900}}, cloud: {enabled: false, auto: true, url: '', key: '', code: '', lastError: '', lastSync: 0, remoteAt: 0}, records: {}, sessions: [], daily: {}, aiUsage: {date: '2026-11-03', calls: 0, tin: 0, tout: 0, cost: 0}, aiChat: [], imported: [], importedMeta: {points: [], materials: []}, pending: [], lastPractice: null};
const copy = (x) => JSON.parse(JSON.stringify(x));
let checks = 0;
function check(value) { assert.ok(value); checks++; }
for (const id of ['constructor', 'prototype', '__proto__', 'toString', 'hasOwnProperty', 'valueOf', 'x" onclick="bad', '../x']) check(!s.validId(id));
check(s.validId('q-valid_001'));
for (const value of ['<img src=x>', NaN, Infinity, {}, -2]) check(s.safeNumber(value) === 0);
check(s.safeNumber(42) === 42);
const local = copy(base);
local.settings.ai.key = 'FAKE_API_KEY';
local.settings.ai.remember = false;
local.cloud = {...local.cloud, url:'https://local-sync.invalid', key:'FAKE_ANON_KEY', code:'FAKE_SYNC_CODE_1234', enabled:true};
check(s.persistedState(local).settings.ai.key === '');
check(local.settings.ai.key === 'FAKE_API_KEY');
const payload = s.learningPayload(local);
check(!('ai' in payload.settings) && !('cloud' in payload));
check(!JSON.stringify(payload).includes('FAKE_'));
const incoming = copy(base);
incoming.settings.ai.base = 'https://attacker.invalid';
incoming.settings.ai.key = 'ATTACKER_KEY';
incoming.cloud.url = 'https://attacker.invalid';
incoming.settings.goal = '<img src=x>';
incoming.aiUsage.tin = '<img src=x>';
incoming.records[bank.questions[0].id] = {seen: '<img src=x>', reasons: {'审题偏差': 2}};
incoming.examCfg = {count: 20, min: 25, off: ['ziliao', 'not-a-module']};
const restored = s.restoreState(incoming, local, base, bank);
check(restored.settings.ai.base === local.settings.ai.base && restored.settings.ai.key === 'FAKE_API_KEY');
check(restored.cloud.url === local.cloud.url && restored.cloud.code === local.cloud.code);
check(restored.settings.goal === 20 && restored.aiUsage.tin === 0);
check(restored.records[bank.questions[0].id].seen === 0);
check(JSON.stringify(restored.records[bank.questions[0].id].reasons) === JSON.stringify({'审题偏差': 2}));
check(JSON.stringify(restored.examCfg.off) === '["ziliao"]');
check(s.normalizeState(local, base, bank).settings.ai.key === '');
for (const bad of [null, {}, {records: [], settings: {}}, {records: {}, settings: []}]) { assert.throws(() => s.restoreState(bad, local, base, bank)); checks++; }
for (const url of ['javascript:alert(1)', 'http://remote.invalid', 'https://user:pass@remote.invalid', 'https://remote.invalid/?key=x', 'https://remote.invalid/#x']) check(!s.endpoint(url));
check(s.endpoint('https://valid.invalid/v1') === 'https://valid.invalid/v1');
check(s.endpoint('http://localhost:8787') === 'http://localhost:8787');
console.log(`${checks} pure security state checks passed`);
